import * as protobuf from "protobufjs";

function safeIdentifier(input: string): string {
  const normalized = input.replace(/[^A-Za-z0-9_$]/g, "_");
  return /^[A-Za-z_$]/.test(normalized) ? normalized : `_${normalized}`;
}

function tsSymbol(fullName: string): string {
  return safeIdentifier(fullName.split(".").filter(Boolean).join("__"));
}

function collectTypes(ns: protobuf.Namespace): {
  messages: protobuf.Type[];
  enums: protobuf.Enum[];
} {
  const messages: protobuf.Type[] = [];
  const enums: protobuf.Enum[] = [];

  for (const item of ns.nestedArray) {
    if (item instanceof protobuf.Type) {
      messages.push(item);
      const child = collectTypes(item);
      messages.push(...child.messages);
      enums.push(...child.enums);
    } else if (item instanceof protobuf.Enum) {
      enums.push(item);
    } else if (item instanceof protobuf.Namespace) {
      const child = collectTypes(item);
      messages.push(...child.messages);
      enums.push(...child.enums);
    }
  }

  return { messages, enums };
}

function scalarToTs(protoType: string): string {
  switch (protoType) {
    case "string":
      return "string";
    case "bool":
      return "boolean";
    case "bytes":
      return "Uint8Array";
    case "double":
    case "float":
    case "int32":
    case "sint32":
    case "sfixed32":
    case "uint32":
    case "fixed32":
      return "number";
    // Safe default for JSON-facing TypeScript DTOs; binary generator runtimes may use Long/bigint.
    case "int64":
    case "sint64":
    case "sfixed64":
    case "uint64":
    case "fixed64":
      return "string";
    default:
      return "unknown";
  }
}

/**
 * A deliberately small teaching converter, not a replacement for protoc or a production plugin.
 * Supports scalar fields, message references, enums, repeated fields and map fields for self-contained
 * .proto files. Imports/services/oneof/custom options are intentionally not generated here.
 */
export function generateTypeScript(protoText: string): {
  sourceName: string;
  content: string;
  warnings: string[];
} {
  if (/^\s*import\s+/m.test(protoText)) {
    throw new Error(
      "This demo converter expects a self-contained .proto file; import resolution is not implemented."
    );
  }

  let root: protobuf.Root;
  try {
    root = protobuf.parse(protoText, { keepCase: true }).root;
    root.resolveAll();
  } catch (error) {
    const message = error instanceof Error ? error.message : String(error);
    throw new Error(`Failed to parse/resolve Protobuf: ${message}`);
  }

  const { messages, enums } = collectTypes(root);
  if (messages.length === 0 && enums.length === 0) {
    throw new Error("No message or enum definitions were found in the .proto file.");
  }

  const symbols = new Map<string, string>();
  const nameCounts = new Map<string, number>();
  for (const object of [...messages, ...enums]) {
    const shortName = object.name;
    nameCounts.set(shortName, (nameCounts.get(shortName) ?? 0) + 1);
    symbols.set(object.fullName, tsSymbol(object.fullName));
  }
  const duplicateNames = [...nameCounts.entries()].filter(([, count]) => count > 1);
  if (duplicateNames.length > 0) {
    throw new Error(
      `Duplicate simple type names are ambiguous in this demo: ${duplicateNames
        .map(([name]) => name)
        .join(", ")}`
    );
  }

  const lines: string[] = [
    "/* eslint-disable */",
    "/** Generated by protobuf-mcp-demo. Do not edit by hand. */",
    "/** Educational JSON-facing typings; use your production generator for runtime codecs/API clients. */",
    "",
  ];

  for (const enumType of enums) {
    const enumName = symbols.get(enumType.fullName) ?? safeIdentifier(enumType.name);
    lines.push(`export enum ${enumName} {`);
    for (const [valueName, value] of Object.entries(enumType.values)) {
      lines.push(`  ${safeIdentifier(valueName)} = ${value},`);
    }
    lines.push("}", "");
  }

  for (const message of messages) {
    if (message.oneofsArray.length > 0) {
      throw new Error(
        `Message ${message.fullName} contains oneof; this demo converter does not generate oneof unions.`
      );
    }

    const messageName = symbols.get(message.fullName) ?? safeIdentifier(message.name);
    lines.push(`export interface ${messageName} {`);

    for (const field of message.fieldsArray) {
      let valueType = scalarToTs(field.type);
      if (field.resolvedType) {
        valueType = symbols.get(field.resolvedType.fullName) ?? safeIdentifier(field.resolvedType.name);
      }

      if (field.map) {
        // Object keys in JSON are strings, even when the Protobuf map key is numeric.
        valueType = `Record<string, ${valueType}>`;
      } else if (field.repeated) {
        valueType = `${valueType}[]`;
      }

      const optionalMark = field.repeated || field.map ? "" : "?";
      lines.push(`  ${safeIdentifier(field.name)}${optionalMark}: ${valueType};`);
    }

    lines.push("}", "");
  }

  const warnings = [
    "This educational converter generates TypeScript declarations only; it does not generate runtime codecs or HTTP/gRPC clients.",
    "Protobuf 64-bit integer fields are represented as string for JSON-facing DTO safety; confirm this mapping against your production generator.",
  ];

  return {
    sourceName: "contract.types.ts",
    content: lines.join("\n"),
    warnings,
  };
}
